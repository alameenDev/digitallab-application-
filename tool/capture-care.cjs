const { chromium } = require('playwright');
const fs = require('fs');
(async () => {
  fs.mkdirSync('previews', { recursive: true });
  const browser = await chromium.launch({ headless: true, args: ['--no-sandbox'] });
  const page = await browser.newPage({ viewport: { width: 1366, height: 1000 } });
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto('http://127.0.0.1:8001', { waitUntil: 'networkidle' });
  await page.waitForFunction(() => document.querySelector('flutter-view'), null, { timeout: 60000 });
  await page.waitForTimeout(2000);
  const semantics = page.locator('flt-semantics-placeholder');
  if (await semantics.count()) await semantics.evaluate(e => e.click());
  await page.waitForTimeout(600);
  await page.screenshot({ path: 'previews/care-admin-desktop.png' });
  await page.setViewportSize({ width: 390, height: 1000 });
  await page.waitForTimeout(700);
  await page.screenshot({ path: 'previews/care-admin-mobile.png' });
  const doctors = page.getByText('الأطباء', { exact: true });
  await doctors.dispatchEvent('click');
  await page.getByRole('button', { name: 'إضافة طبيب', exact: true }).waitFor();
  await page.waitForTimeout(500);
  await page.screenshot({ path: 'previews/doctor-management-mobile.png' });
  console.log('CARE_ADMIN_DESKTOP_BASE64=' + fs.readFileSync('previews/care-admin-desktop.png').toString('base64'));
  console.log('CARE_DOCTORS_MOBILE_BASE64=' + fs.readFileSync('previews/doctor-management-mobile.png').toString('base64'));
  fs.writeFileSync('previews/care-browser-errors.json', JSON.stringify(errors, null, 2));
  await browser.close();
  if (errors.length) throw new Error(errors.join('\n'));
})().catch(e => { console.error(e); process.exit(1); });
